def write_indexes():
    order = {f"week-{w}": i for i, w in enumerate(WEEK_ORDER)}
    nodes = []
    for i, d in DOCS.items():
        nodes.append(dict(id=i, type=d["type"], title=d["title"], path=d["path"], parent=d["parent"], children=d["children"], week=d["week"],
                          order=order.get(i), source_url=(d["source_urls"][0] if d["source_urls"] else None), source_urls=d["source_urls"],
                          source_type=d["source_type"], status=d["review_status"], tags=sorted(set(d["tags"]))))
    for path, typ, owner, src in EXTRA_FILES:
        nodes.append(dict(id=f"file:{path}", type=typ, title=os.path.basename(path), path=path, parent=owner, children=[], week=DOCS[owner]["week"],
                          order=None, source_url=src, source_urls=[src], source_type="official", status="verified-against-source", tags=[typ]))
    json.dump(dict(generated_at=BUILD_TIME, root="project", license_notice="LICENSE-NOTICE.md", node_count=len(nodes), nodes=nodes),
              open(os.path.join(KB, "index.json"), "w"), indent=1, ensure_ascii=False)
    edges = []
    for i, d in DOCS.items():
        if d["parent"]: edges.append(dict(source=d["parent"], target=i, type="parent-of"))
        for t in d["prerequisites"]: edges.append(dict(source=t, target=i, type="prerequisite-of"))
        for t in sorted(set(d["related"]) - {i}): edges.append(dict(source=i, target=t, type="related"))
    for path, typ, owner, src in EXTRA_FILES: edges.append(dict(source=owner, target=f"file:{path}", type="has-file"))
    json.dump(edges, open(os.path.join(KB, "edges.json"), "w"), indent=1, ensure_ascii=False)
    n = 0
    with open(os.path.join(KB, "search.jsonl"), "w", encoding="utf-8") as f:
        def emit(rec):
            nonlocal n
            f.write(json.dumps(rec, ensure_ascii=False) + "\n"); n += 1
        for i, d in DOCS.items():
            text = open(os.path.join(KB, d["path"]), encoding="utf-8").read().split("\n---\n", 1)[1]
            state = dict(h=d["title"], st="metadata", buf=[], k=0)
            def flush():
                t = "\n".join(state["buf"]).strip()
                for j in range(0, len(t), 2000):
                    piece = t[j:j+2000]
                    if piece.strip():
                        emit(dict(id=f"{i}#{state['k']}", doc_id=i, path=d["path"], heading=state["h"], text=piece,
                                  source_url=(d["source_urls"][0] if d["source_urls"] else None), source_type=state["st"],
                                  doc_type=d["type"], week=d["week"], tags=sorted(set(d["tags"]))))
                        state["k"] += 1
                state["buf"] = []
            infence = False
            for line in text.splitlines():
                if line.startswith("```"): infence = not infence
                if not infence and re.match(r"^#{1,4} ", line):
                    flush(); state["h"] = line.lstrip("# ").strip()
                    if line.startswith("## "):
                        state["st"] = ("official" if d["source_type"] != "generated" else "generated") if "OFFICIAL" in line else ("generated" if "GENERATED" in line else "metadata")
                    elif line.startswith("### ") and "GENERATED" in line: state["st"] = "generated"
                    elif line.startswith("### ") and "Stated by source" in line: state["st"] = "official"
                    continue
                state["buf"].append(line)
            flush()
        for path, typ, owner, src in EXTRA_FILES:
            t = open(os.path.join(KB, path), encoding="utf-8").read()
            for j in range(0, len(t), 2000):
                emit(dict(id=f"file:{path}#{j//2000}", doc_id=owner, path=path, heading=f"transcript ({os.path.basename(path)})", text=t[j:j+2000],
                          source_url=src, source_type="official", doc_type=typ, week=DOCS[owner]["week"], tags=["transcript"]))
    return n

