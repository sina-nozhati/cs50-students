MAXF = 100 * 1024

def extract_zip(url, dest_dir):
    """Store small UTF-8 text files verbatim; return (inventory rows, error)."""
    e = M.get(url)
    if not e: return [], "zip not in manifest"
    if e.get("status") != "fetched": return [], f"zip {e.get('status')}: {e.get('reason')}"
    rows = []
    try:
        z = zipfile.ZipFile(os.path.join(B, e["file"]))
    except Exception as ex:
        return [], f"zip unreadable: {ex}"
    for i in z.infolist():
        if i.is_dir() or "__MACOSX" in i.filename or os.path.basename(i.filename).startswith("._"): continue
        stored, why = False, ""
        if not TEXT_EXT.search(i.filename): why = "binary/media/data file (inventory only)"
        elif i.file_size > MAXF: why = f"text file larger than {MAXF//1024} KB (inventory only)"
        else:
            data = z.read(i)
            try:
                data.decode("utf-8")
                tgt = os.path.join(dest_dir, "files", i.filename)
                os.makedirs(os.path.dirname(os.path.join(KB, tgt)), exist_ok=True)
                open(os.path.join(KB, tgt), "wb").write(data); stored = True
            except UnicodeDecodeError:
                why = "not UTF-8 text (inventory only)"
        rows.append(dict(path=i.filename, bytes=i.file_size, stored=stored, reason=why,
                         local=os.path.join(dest_dir, "files", i.filename) if stored else None))
    return rows, None

def listing_inventory(root_url, dest_dir):
    rows = []
    for u, e in sorted(M.items()):
        if not u.startswith(root_url) or u.endswith("/") or e.get("category") != "cdn-listing-file": continue
        relp = u[len(root_url):]
        MAPPED_URLS.add(u)
        if e.get("status") == "fetched":
            tgt = os.path.join(dest_dir, "files", relp)
            os.makedirs(os.path.dirname(os.path.join(KB, tgt)), exist_ok=True)
            shutil.copyfile(os.path.join(B, e["file"]), os.path.join(KB, tgt))
            rows.append(dict(path=relp, bytes=e.get("bytes"), stored=True, reason="", local=tgt))
        else:
            rows.append(dict(path=relp, bytes=e.get("bytes"), stored=False, reason=e.get("reason", ""), local=None))
    return rows

def inventory_md(doc_path, rows):
    if not rows: return "_No files inventoried._"
    out = ["| File | Bytes | Stored in KB |", "|---|---:|---|"]
    for r in rows:
        st = f"[yes]({rel(doc_path, r['local'])})" if r["stored"] else f"no — {r['reason']}"
        out.append(f"| `{r['path']}` | {r['bytes'] if r['bytes'] is not None else '?'} | {st} |")
    return "\n".join(out)

def find_zips(page_url):
    txt = (raw_bytes(page_url) or b"").decode("utf-8", "ignore")
    return sorted(set(re.findall(r"https://cdn\.cs50\.net/[^\s\"'<>`)]+?\.zip", txt)))

