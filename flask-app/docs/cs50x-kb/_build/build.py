def collect_passages():
    for w in [0,1,2,3,4,5,6,7,"ai",8,9,10]:
        url = f"https://cs50.harvard.edu/x/notes/{w}/"
        s = soup(url)
        if s is None: continue
        m = s.select_one("main")
        for t in m.select("#markdown-toc"): t.decompose()
        head, anchor, pos = None, None, 0
        for el in m.find_all(["h2", "h3", "p", "li"]):
            if el.name in ("h2", "h3"):
                head, anchor = el.get_text(" ", strip=True), el.get("id"); continue
            if el.name == "li" and el.find("p"): continue
            if el.find_parent("pre"): continue
            c = BeautifulSoup(str(el), "lxml")
            for x in c.find_all(["ul", "ol", "pre", "div"]): x.decompose()
            text = c.get_text(" ", strip=True)
            text = re.sub(r"\s+([,.;:!?])", r"\1", text)
            if len(text) < 25 or not anchor: continue
            pos += 1
            PASSAGES.append(dict(week=w, url=url, anchor=anchor, heading=head, text=text, pos=pos,
                                 ems=[e.get_text(" ", strip=True) for e in el.find_all("em") if not e.find_parent("code")]))

