def build_glossary():
    terms = {}
    stop = {"not", "very", "all", "any", "one", "two", "this", "that", "and", "or", "only", "each", "every", "must", "really", "should", "can", "will", "your", "you", "is", "are", "the", "same", "both"}
    for p in PASSAGES:
        for t in p["ems"]:
            t2 = t.strip(" .,:;!?\"“”'")
            if not (3 <= len(t2) <= 40) or len(t2.split()) > 4 or t2.lower() in stop or not re.match(r"^[A-Za-z][A-Za-z0-9 \-/+]*$", t2): continue
            esc = re.escape(t2)
            if re.search(esc + r"\s*(,|\(|\bis\b|\bare\b|\brefers\b|\bmeans\b)", p["text"]) or re.search(r"(called|known as|termed)\s+(an?\s+|the\s+)?" + esc, p["text"], re.I):
                terms.setdefault(t2.lower(), dict(term=t2, src=[]))["src"].append(p)
    for slug, c in CONCEPTS.items():
        terms.setdefault(c["title"].lower(), dict(term=c["title"], src=[]))["concept"] = f"concept-{slug}"
    lines = []
    for k in sorted(terms):
        t = terms[k]
        lines.append(f"### {t['term']}")
        if t.get("concept"): lines.append(f"- Concept doc: [{DOCS[t['concept']]['title']}]({rel('glossary.md', DOCS[t['concept']]['path'])})")
        if t["src"]:
            p = t["src"][0]
            lines.append(f"- Definition source (verbatim sentence; {week_label(p['week'])} notes, “{p['heading']}”):\n\n  > {p['text']}\n")
            lines.append(f"  - Source: <{p['url']}#{p['anchor']}> · KB: [{week_label(p['week'])} lecture]({rel('glossary.md', DOCS['week-' + str(p['week']) + '-lecture']['path'])}#{p['anchor']})")
            if len(t["src"]) > 1:
                lines.append("- Also used in: " + ", ".join(sorted({f"{week_label(q['week'])} “{q['heading']}”" for q in t["src"][1:]})))
        lines.append("")
    add("glossary", type="glossary", title="Glossary (terms → definition source → linked docs)", path="glossary.md", parent="course",
        source_type="mixed", review_status="partially-verified", source_urls=[f"https://cs50.harvard.edu/x/notes/{w}/" for w in WEEK_ORDER],
        tags=["glossary"], official=f"Terms were extracted automatically: an *italicised* term in the lecture notes followed by a definition cue (`,` `(` `is` `are` `refers` `means`) or preceded by *called / known as*; plus every concept title. The quoted sentence is verbatim from the notes. {len(terms)} entries.\n\n" + "\n".join(lines),
        gaps=["Automatic term extraction: some entries are emphasis rather than definitions; defined terms that are not italicised are missing."],
        gen_app="### کاربرد (تولیدشده)\n- مبنای واژه‌نامه‌ی فارسی سایت: برای هر اصطلاح، معادل فارسی و توضیح کوتاه اضافه شود و جمله‌ی رسمی منبع حفظ شود.")
    link_children("course", "glossary")
    return len(terms)

