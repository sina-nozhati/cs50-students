def main_md(url, level=2, drop_h1=False):
    s = soup(url)
    if s is None: return None
    m = s.select_one("main") or s.select_one("div[role=main]") or s.select_one("article") or s.body
    if drop_h1:
        h = m.find("h1")
        if h: h.decompose()
    MAPPED_URLS.add(url)
    return demote(to_md(m, ent(url).get("final_url") or url), level)

